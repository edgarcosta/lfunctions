/*
   Regression test for bead lfunctions-0zo (Booker/Turing RH confirmation,
   turing_check_RH in src/turing.c).

   We drive a genuine degree-4 L-function through the PUBLIC API only
   (glfunc.h): the L-function of the genus-2 curve 169.a.169.1 (LMFDB),
       y^2 + (x^3 + x + 1) y = x^5 + x^4,
   conductor N = 13^2 = 169, motivic weight 1, self-dual, analytic
   normalisation 1/2 (mus = [0,0,1,1]).  Its Euler factors below are the
   arithmetic-normalised integer L-polynomials 1 + c1 T + c2 T^2 + c1 p T^3 +
   p^2 T^4 (degree 2 at the bad prime 13: 1 + 5T + 13T^2), generated by
   brute-force point counting over F_p and F_{p^2} and cross-checked against
   LMFDB's stored euler_factors for p < 100.

   What this test pins (all via certified arb/acb overlaps, never printed text):
     - the computation is not fatal;
     - the numeric core is correct: |eps| = 1, eps = +1 (LMFDB root_number),
       and the first zero overlaps the LMFDB value 5.0682346354060292504.

   On ERR_RH_ERROR: the bead's headline symptom was the "Found too many zeros"
   branch of turing_check_RH firing for EVERY degree>=3 L-function.  That branch
   was genuinely miscalibrated -- it used the analytic LOWER bound of the Turing
   count as a contradiction signal, but the isolated zeros are a rigorous LOWER
   bound on N(t0), so a loose analytic lower bound is no contradiction.  This
   commit corrects the branch (it now flags "too many" only when the analytic
   UPPER bound drops below the count actually found).

   The corrected check no longer raises the false "too many" alarm, but it
   cannot by itself CONFIRM completeness for this degree-4 object: the rigorous
   bound on int S(t) dt has a leading term proportional to the degree r, while
   the Turing window h = B/TURING_RATIO = 32/r shrinks with r (B = 512/r), so
   the count's half-width exceeds 1 for r >= 3 and the honest verdict is "too
   few" (a possibly-missed zero cannot be ruled out).  Widening the window is an
   out-of-scope grid-scaling change (B / OUTPUT_RATIO / TURING_RATIO live in
   g.c / glfunc_internals.h), so we TOLERATE ERR_RH_ERROR here -- as the
   sibling high-degree suite (bead lfunctions-8dz) already does -- and assert
   the numeric core, which is and remains correct.

   Exit code is the oracle: 0 = all assertions passed (asserts abort otherwise).
*/

