int main(void)
{
  fmpz_poly_t got, want;
  fmpz_poly_init(got);
  fmpz_poly_init(want);
  fmpz_t c;
  fmpz_init(c);

  const int ncases = (int) (sizeof(CASES) / sizeof(CASES[0]));
  int fail = 0;
  for (int i = 0; i < ncases; i++) {
    const sym_case_t *tc = &CASES[i];
    sym_power_lpoly(got, tc->a_p, tc->p, tc->k);

    fmpz_poly_zero(want);
    for (int j = 0; j < tc->len; j++) {
      fmpz_set_str(c, tc->coeffs[j], 10);
      fmpz_poly_set_coeff_fmpz(want, j, c);
    }

    if (!fmpz_poly_equal(got, want)) {
      fail = 1;
      printf("FAIL  k=%d p=%lu a_p=%ld\n", tc->k, (unsigned long) tc->p, (long) tc->a_p);
      printf("  got : "); fmpz_poly_print_pretty(got, "T"); printf("\n");
      printf("  want: "); fmpz_poly_print_pretty(want, "T"); printf("\n");
    }
  }

  if (!fail)
    printf("sympow_lpoly_test: all %d cases passed\n", ncases);

  fmpz_clear(c);
  fmpz_poly_clear(got);
  fmpz_poly_clear(want);
  return fail;
}
